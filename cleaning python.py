import pandas as pd

import numpy as np

df = pd.read_excel(r"/content/CarbonIQ2.xlsx")
df

df.info()

print(df.duplicated().sum())

df_filtered=df.iloc[:, [0,3,4,5,12,13,14,15,16,48,49,50,51,52]]

df=df_filtered
df

df.columns=df.columns.str.strip().str.lower().str.replace(' ','_')
df

df= df.rename(columns={
    'industry_type_(sectors)':'industry_sector',
    'total_reported_direct_emissions': 'total_direct_emissions',
    'co2_emissions_(non-biogenic)':'CO2_emissions',
    'methane_(ch4)_emissions': 'CH4_emissions',
    'nitrous_oxide_(n2o)_emissions':'N2O_emissions',
    'total_major_greenhouse_gases':'total_major_ghg',
    'methane_share_%':'CH4_share_pct',
    'co2_share%':'CO2_share_pct'})
df

columns=["facility_name","city","industry_sector","emission_category","emission_category"]

for c in columns:
  df[c] = df[c].astype("string").str.strip().str.title()

df

df.info()

numeric_columns = df.select_dtypes(include=['float64', 'int64']).columns

for column in numeric_columns:
    df.loc[df[column] < 0, column] = np.nan

percentage_cols = ['CH4_share_pct', 'CO2_share_pct']

for col in percentage_cols:
    df.loc[df[col] > 100, col] = np.nan

subset_cols = ['facility_name', 'city', 'state', 'year']

df = df.drop_duplicates(subset=subset_cols, keep='first')

df['year'] = df['year'].astype(int)

text_columns = df.select_dtypes(include=['object']).columns

for col in text_columns:
    df[col]=df[col].replace("",pd.NA)

facility_col = 'facility_name'
numerical_cols = [
    'total_direct_emissions', 'CH4_emissions',
    'total_major_ghg', 'CO2_share_pct','CH4_share_pct']

for col in numerical_cols:
    df[col] = df[col].fillna(df.groupby(facility_col)[col].transform('median'))

df.info()

